#!/usr/bin/env python3
"""Render generated blocks from the inventory.

  <inventory>/AGENTS.md               <!-- GENERATED: current-state -->
  <inventory>/sites/<id>/README.md    <!-- GENERATED: site-state -->

--check exits 1 if any file would change (used by pre-commit).
"""
from __future__ import annotations

import sys
from pathlib import Path

from invlib import INV, ROOT, get, load_inventory, replace_block, site_dir


def shown(p: Path) -> str:
    for base in (ROOT, INV):
        try:
            return str(p.resolve().relative_to(base.resolve()))
        except ValueError:
            continue
    return str(p)


def short(d: str, n: int = 12) -> str:
    if not d:
        return ""
    d = str(d)
    if d.startswith("sha256:") and len(d) > 7 + n:
        return d[: 7 + n] + "…"
    return d


def site_role(s: dict) -> str:
    kind = s.get("kind")
    stacks = ", ".join(st.get("id", "") for st in s.get("stacks") or [])
    if kind == "public-node":
        roles = ", ".join(n.get("role", "full") for n in s.get("nodes") or [])
        return f"{roles} structsd; dependents: {', '.join(s.get('dependents') or [])}"
    if kind == "guild":
        nodes = ", ".join(n.get("role", "full") for n in s.get("nodes") or [])
        return f"stacks: {stacks}" + (f"; structsd: {nodes}" if nodes else "")
    return f"stacks: {stacks}"


def site_specifics(sid: str, s: dict) -> list[str]:
    bits = []
    for src in s.get("sources") or []:
        if src.get("commit") or src.get("pin_reason"):
            bits.append(f"{src['repo']} `{src.get('ref')}@{src.get('commit', '')}`"
                        + (f" ({src['pin_reason']})" if src.get("pin_reason") else ""))
    for st in s.get("stacks") or []:
        for svc, conf in (st.get("services") or {}).items():
            conf = conf or {}
            env = conf.get("env") or {}
            if "TSA_WORKERS" in env:
                bits.append(f"{svc} `TSA_WORKERS={env['TSA_WORKERS']}`")
            if env.get("STRUCTS_PG_BRANCH") and svc.endswith("auto-migrate"):
                bits.append(f"{svc} tracks structs-pg `{env['STRUCTS_PG_BRANCH']}` (never re-pin)")
            if conf.get("pool"):
                bits.append(f"{svc} pools {conf['pool']}")
    ign = get(s, "checks.ignore_unhealthy") or []
    if ign:
        bits.append("ignore unhealthy: " + ", ".join(ign))
    g = get(s, "onchain.guild")
    if g:
        bits.append(f"guild `{g.get('id')}` endpoint {g.get('endpoint')}")
    v = get(s, "onchain.validator")
    if v:
        bits.append(f"validator `{v.get('moniker')}`")
    crit = [n for n, x in (s.get("secrets") or {}).items()
            if x.get("criticality") == "critical" and str(x.get("backup")).lower() == "none"]
    if crit:
        bits.append("critical secrets with no off-host backup: " + ", ".join(crit))
    ki = [k.get("id") for k in s.get("known_issues") or []]
    if ki:
        bits.append("known issues: " + ", ".join(ki))
    return bits


def current_state(net: dict, sites: dict) -> str:
    b = net.get("binary") or {}
    img = get(net, "images.structsd") or {}
    voters = ", ".join(f"{v['site']}.{v['account']}" for v in get(net, "gov.voters") or [])
    image = (f", image `{img.get('repo')}:{img.get('tag', 'latest')}` @ `{short(img.get('digest'))}` ({img.get('date')})"
             if img.get("digest") else "")
    pub = net.get("public_node_site")
    lines = [
        "_Generated by `devops inventory render` from `inventory/`. Edit the inventory, not this block._",
        "",
        f"- **Chain** `{net.get('chain_id')}`: structsd **{b.get('version')}** since height {b.get('since_height')}"
        f" (`cosmovisor/current -> {b.get('cosmovisor_current')}`){image}."
        f" Block time ~{net.get('block_time_seconds')} s.",
        f"- **Public endpoints:** RPC `{get(net, 'endpoints.rpc')}`, LCD `{get(net, 'endpoints.lcd')}`"
        + (f" (served by site `{pub}`)." if pub else " (served by someone else; none of these sites)."),
        f"- **Gov voters:** {voters or 'none'} (votes are never automatic).",
        "",
        "| Site | Kind | SSH | Runs |",
        "|---|---|---|---|",
    ]
    for sid, s in sites.items():
        kind = s.get("kind")
        if kind == "guild" and get(s, "onchain.guild.id"):
            kind = f"guild `{get(s, 'onchain.guild.id')}`"
        sshs = ", ".join(f"`{h.get('ssh')}`" for h in s.get("hosts") or [])
        lines.append(f"| `{sid}` | {kind} | {sshs} | {site_role(s)} |")
    lines.append("")
    for sid, s in sites.items():
        bits = site_specifics(sid, s)
        if bits:
            lines.append(f"- **{sid}** (verified {s.get('last_verified')}): " + "; ".join(bits) + ".")
    return "\n".join(lines)


def site_state(sid: str, s: dict) -> str:
    L = ["_Generated by `devops inventory render` from `site.yaml`. Edit `site.yaml`, not this block._", ""]
    L += [f"**Kind:** {s.get('kind')}  **Network:** {s.get('network')}  **Last verified:** {s.get('last_verified')}", ""]
    L += ["| Host | FQDN | IPv4 | SSH | Tools path |", "|---|---|---|---|---|"]
    for h in s.get("hosts") or []:
        L.append(f"| `{h.get('id')}` | {h.get('fqdn', '')} | {h.get('ipv4', '')} | `{h.get('ssh')}` | `{h.get('tools_path', '')}` |")
    L += ["", "| Stack | Host | Path | Services |", "|---|---|---|---|"]
    for st in s.get("stacks") or []:
        svcs = []
        for name, conf in (st.get("services") or {}).items():
            conf = conf or {}
            extra = []
            if conf.get("digest"):
                extra.append(short(conf["digest"]))
            for k, v in (conf.get("env") or {}).items():
                if k in ("TSA_WORKERS", "STRUCTS_PG_BRANCH", "STRUCTS_PG_MIGRATION_MODE"):
                    extra.append(f"{k}={v}")
            svcs.append(name + (f" ({', '.join(extra)})" if extra else ""))
        files = ", ".join(st.get("compose") or ["compose.yaml"])
        L.append(f"| `{st.get('id')}` | {st.get('host')} | `{st.get('path')}` ({files}) | {'; '.join(svcs)} |")
    if s.get("nodes"):
        L += ["", "| structsd node | Role | Container | Volume |", "|---|---|---|---|"]
        for n in s["nodes"]:
            L.append(f"| {n.get('host')} | {n.get('role', 'full')} | `{n.get('container')}` | `{n.get('volume', 'structsd-chaindata')}` |")
    if s.get("onchain"):
        o = s["onchain"]
        g = o.get("guild") or {}
        L += [""]
        if g:
            L.append(f"**Guild** `{g.get('id')}` {g.get('name', '')}: endpoint {g.get('endpoint')}, entry substation `{g.get('entry_substation', '')}`, reactor `{g.get('primary_reactor', '')}`, player `{o.get('player', '')}`.")
        if o.get("validator"):
            L.append(f"**Validator** `{o['validator'].get('moniker')}`: `{o['validator'].get('operator')}`.")
        for a, d in (o.get("accounts") or {}).items():
            L.append(f"**Account** `{a}`: `{d.get('address')}` (secret `{d.get('secret')}`{', gov voter' if d.get('gov_voter') else ''}).")
    if s.get("secrets"):
        L += ["", "| Secret | Pointer | Criticality | Backup |", "|---|---|---|---|"]
        for n, d in s["secrets"].items():
            L.append(f"| `{n}` | `{d.get('ref')}` | {d.get('criticality')} | {d.get('backup')} |")
    if s.get("endpoints"):
        L += ["", "Endpoints: " + ", ".join(f"`{e['id']}`" for e in s["endpoints"]) + " (checked by `devops check endpoints " + sid + "`)."]
    if s.get("procedures"):
        L += ["", "Procedures (`devops deploy " + sid + " <name> --dry-run`):"]
        for p, d in s["procedures"].items():
            L.append(f"- `{p}`: {(d or {}).get('description', '')}")
    if s.get("known_issues"):
        L += ["", "| Known issue | Symptom | Fix |", "|---|---|---|"]
        for k in s["known_issues"]:
            L.append(f"| `{k.get('id')}` | {k.get('symptom', '')} | {k.get('fix', '')} |")
    return "\n".join(L)


def main():
    check = "--check" in sys.argv
    net, sites = load_inventory()
    targets = [(INV / "AGENTS.md", "current-state", current_state(net, sites))]
    for sid, s in sites.items():
        targets.append((site_dir(sid) / "README.md", "site-state", site_state(sid, s)))
    changed = []
    for path, name, body in targets:
        old = path.read_text() if path.exists() else f"# {path.parent.name}\n"
        new = replace_block(old, name, body)
        if new != old:
            changed.append(path)
            if not check:
                path.write_text(new)
    for p in changed:
        print(("would update " if check else "updated ") + shown(p))
    if not changed:
        print("generated blocks are up to date")
    sys.exit(1 if (check and changed) else 0)


if __name__ == "__main__":
    main()
